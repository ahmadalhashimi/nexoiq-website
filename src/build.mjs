#!/usr/bin/env node
// NexoIQ static site generator — no dependencies, Node 18+.
//
//   node src/build.mjs
//
// Generates static HTML for every page in EN (/), NL (/nl/) and AR (/ar/) into
// the repository root, which is what Netlify already publishes. The generated
// files are committed, so Netlify needs no build command and no settings change.
//
// Steps: validate content → clean old output → render pages → copy assets →
// sitemap/robots → check every internal link and anchor.

import { readFile, writeFile, mkdir, rm, cp, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { SITE, LANGS, DEFAULT_LANG, PAGES } from './site.config.mjs';
import { href, absUrl } from './components/util.mjs';
import { Layout } from './components/Layout.mjs';
import en from './content/en.mjs';
import nl from './content/nl.mjs';
import ar from './content/ar.mjs';

import Home from './pages/Home.mjs';
import DataEngineering from './pages/DataEngineering.mjs';
import OdooConsulting from './pages/OdooConsulting.mjs';
import ERPIntegration from './pages/ERPIntegration.mjs';
import Training from './pages/Training.mjs';
import About from './pages/About.mjs';
import Contact from './pages/Contact.mjs';
import { Privacy, Thanks, NotFound } from './pages/Simple.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = { en, nl, ar };
const RENDER = {
  home: Home, dataEngineering: DataEngineering, odoo: OdooConsulting, integration: ERPIntegration,
  training: Training, about: About, contact: Contact, privacy: Privacy, thanks: Thanks,
};
const BANNER = '<!-- Generated by src/build.mjs. Do not edit: change files in src/ and rebuild. -->';

// ---------------------------------------------------------------- 1. validate
function compareShape(ref, other, where, errors) {
  if (Array.isArray(ref)) {
    if (!Array.isArray(other)) return errors.push(`${where}: expected a list`);
    if (ref.length !== other.length) errors.push(`${where}: list has ${other.length} items, English has ${ref.length}`);
    ref.forEach((r, i) => other[i] !== undefined && compareShape(r, other[i], `${where}[${i}]`, errors));
  } else if (ref && typeof ref === 'object') {
    if (!other || typeof other !== 'object') return errors.push(`${where}: expected an object`);
    for (const k of Object.keys(ref)) {
      if (!(k in other)) errors.push(`${where}.${k}: missing`);
      else compareShape(ref[k], other[k], `${where}.${k}`, errors);
    }
    for (const k of Object.keys(other)) if (!(k in ref)) errors.push(`${where}.${k}: not in English`);
  } else if (typeof other !== 'string' || !other.trim()) {
    errors.push(`${where}: empty or not text`);
  }
}

const errors = [];
for (const l of LANGS) if (l !== 'en') compareShape(en, CONTENT[l], l, errors);
for (const p of PAGES) if (!RENDER[p.id]) errors.push(`No renderer for page "${p.id}"`);
if (errors.length) {
  console.error('Content validation failed:\n  ' + errors.join('\n  '));
  process.exit(1);
}

// ---------------------------------------------------------------- 2. clean
const topDirs = new Set(PAGES.map((p) => p.slug.split('/')[0]).filter(Boolean));
const GENERATED = ['index.html', '404.html', 'robots.txt', 'sitemap.xml', 'favicon.png', 'assets', 'images',
  ...LANGS.filter((l) => l !== DEFAULT_LANG), ...topDirs];
for (const g of GENERATED) await rm(path.join(ROOT, g), { recursive: true, force: true });

// ---------------------------------------------------------------- 3. render
const written = [];
async function out(rel, html) {
  const file = path.join(ROOT, rel);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, html.replace('<!DOCTYPE html>\n', `<!DOCTYPE html>\n${BANNER}\n`), 'utf8');
  written.push(rel.replace(/\\/g, '/'));
}

for (const lang of LANGS) {
  const t = CONTENT[lang];
  for (const page of PAGES) {
    const r = RENDER[page.id](lang, t);
    const html = Layout({ lang, t, pageId: page.id, noindex: page.noindex || r.noindex, ...r });
    await out(path.join(href(lang, page.id).slice(1), 'index.html'), html);
  }
}
{
  const r = NotFound('en', en, CONTENT);
  await out('404.html', Layout({ lang: 'en', t: en, pageId: null, ...r }));
}

// ---------------------------------------------------------------- 4. assets
const css = await Promise.all(['global.css', 'navigation.css', 'services.css'].map((f) => readFile(path.join(ROOT, 'src/styles', f), 'utf8')));
await mkdir(path.join(ROOT, 'assets'), { recursive: true });
await writeFile(path.join(ROOT, 'assets/site.css'), `/* Generated from src/styles/*.css by src/build.mjs */\n${css.join('\n')}`);
const SCRIPTS = { 'animations.js': 'site.js', 'calculator.js': 'calculator.js', 'contact-form.js': 'contact-form.js' };
for (const [src, dest] of Object.entries(SCRIPTS)) await cp(path.join(ROOT, 'src/scripts', src), path.join(ROOT, 'assets', dest));
await cp(path.join(ROOT, 'public'), ROOT, { recursive: true });

// ---------------------------------------------------------------- 5. SEO files
const today = new Date().toISOString().slice(0, 10);
const indexable = PAGES.filter((p) => !p.noindex);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${indexable.flatMap((p) => LANGS.map((l) => `  <url>
    <loc>${absUrl(href(l, p.id))}</loc>
    <lastmod>${today}</lastmod>
${LANGS.map((a) => `    <xhtml:link rel="alternate" hreflang="${a}" href="${absUrl(href(a, p.id))}"/>`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${absUrl(href(DEFAULT_LANG, p.id))}"/>
  </url>`)).join('\n')}
</urlset>
`;
await writeFile(path.join(ROOT, 'sitemap.xml'), sitemap);
await writeFile(path.join(ROOT, 'robots.txt'), `User-agent: *\nAllow: /\nDisallow: /src/\nDisallow: /docs/\n\nSitemap: ${SITE.url}/sitemap.xml\n`);

// ---------------------------------------------------------------- 6. link check
async function exists(p) { try { await stat(p); return true; } catch { return false; } }
const htmlCache = new Map();
async function html(rel) {
  if (!htmlCache.has(rel)) htmlCache.set(rel, await readFile(path.join(ROOT, rel), 'utf8'));
  return htmlCache.get(rel);
}
const broken = [];
for (const file of written) {
  const src = await html(file);
  const refs = [...src.matchAll(/\s(?:href|src|action)="([^"]+)"/g)].map((m) => m[1]);
  for (const ref of refs) {
    if (/^(https?:|mailto:|tel:|data:)/.test(ref)) continue;
    const [pathPart, hash] = ref.split('#');
    let target = file;
    if (pathPart) {
      if (!pathPart.startsWith('/')) { broken.push(`${file}: relative link "${ref}"`); continue; }
      const clean = pathPart.split('?')[0];
      target = clean.endsWith('/') ? clean.slice(1) + 'index.html' : clean.slice(1);
      if (!(await exists(path.join(ROOT, target)))) { broken.push(`${file}: missing target "${ref}"`); continue; }
    }
    if (hash && target.endsWith('.html')) {
      const t = await html(target);
      if (hash !== 'main' && hash !== 'top' && !t.includes(`id="${hash}"`)) broken.push(`${file}: missing anchor "${ref}"`);
    }
  }
}
if (broken.length) {
  console.error('Broken internal links:\n  ' + [...new Set(broken)].join('\n  '));
  process.exit(1);
}

console.log(`Built ${written.length} pages (${LANGS.join(', ')}) + assets, sitemap.xml, robots.txt. All internal links OK.`);
